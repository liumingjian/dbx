    /** Each ADR-0011 element toggled on and off, and its rendered fragment present exactly when it is on. */
    @Test
    void eachAdr0011ElementToggledChangesTheTextAndTheFingerprint() {
        TargetTable off = table(List.of(
                new TargetColumn(id("id"), BIGINT, Nullability.NULLABLE),
                new TargetColumn(id("k"), BIGINT, Nullability.NOT_NULL),
                new TargetColumn(id("status"), TEXT, Nullability.NULLABLE)), List.of());
        record Toggle(String element, TargetTable on, String fragment) {
        }
        List<Toggle> toggles = List.of(
                new Toggle("nullability", replace(off, 0, new TargetColumn(id("id"), BIGINT, Nullability.NOT_NULL)),
                        "\"id\" bigint NOT NULL"),
                new Toggle("default", replace(off, 0, new TargetColumn(id("id"), BIGINT, Nullability.NULLABLE,
                        Optional.of(new TargetDefault.Literal(new SqlValue.Int64(7))), IdentityIntent.NONE, List.of())),
                        "DEFAULT 7"),
                new Toggle("identity", replace(off, 0, new TargetColumn(id("id"), BIGINT, Nullability.NOT_NULL,
                        Optional.empty(), IdentityIntent.IDENTITY_BY_DEFAULT, List.of())),
                        "GENERATED BY DEFAULT AS IDENTITY"),
                new Toggle("primary key", new TargetTable(off.table(), off.columns(), List.of(id("k"))),
                        "PRIMARY KEY (\"k\")"),
                new Toggle("ENUM members", replace(off, 2, new TargetColumn(id("status"), TEXT, Nullability.NULLABLE,
                        Optional.empty(), IdentityIntent.NONE, List.of("a"))),
                        "CHECK (\"status\" IN (E'a'))"));
        for (Toggle toggle : toggles) {
            SqlPlan onPlan = PAIR.target().ddlPlan(toggle.on());
            SqlPlan offPlan = PAIR.target().ddlPlan(off);
            assertTrue(String.join("\n", sql(onPlan)).contains(toggle.fragment()),
                    "ADR-0011 §DDL: " + toggle.element() + " on renders " + toggle.fragment() + ": " + sql(onPlan));
            assertFalse(String.join("\n", sql(offPlan)).contains(toggle.fragment()),
                    "ADR-0011 §DDL: " + toggle.element() + " off renders nothing: " + sql(offPlan));
            assertTrue(!onPlan.fingerprint().equals(offPlan.fingerprint()),
                    "ADR-0008 §Plans: toggling " + toggle.element() + " changes the fingerprint");
        }
        assertAllDistinct(off, Map.of(
                "key order a,b", keyed(List.of(id("id"), id("k"))),
                "key order b,a", keyed(List.of(id("k"), id("id")))));
    }

