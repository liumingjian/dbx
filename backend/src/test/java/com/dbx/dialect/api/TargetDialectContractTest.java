    // --- Hostile identifiers and values (ADR-0008 §Plans; TP §7.1) -----------------------------------

    private static final List<String> HOSTILE = List.of(
            "it's", "back\\slash", "$$dollar$$", "`tick`", "new\nline", "cr\rtab\t", "a\"b", "?", "soh",
            "del", "客户订单", "emoji😀", "x\"; DROP TABLE t; --", "'); DROP TABLE t; --", "a''b", "e\\'");

    @Test
    void hostileIdentifiersNeverChangeStatementStructure() {
        List<String> benign = skeleton(sql(PAIR.target().ddlPlan(named("s", "t", "c", "q"))));
        for (String hostile : HOSTILE) {
            SqlPlan plan = PAIR.target().ddlPlan(named(hostile, hostile + "t", hostile + "c", hostile + "q"));
            assertEquals(benign, skeleton(sql(plan)),
                    "TP §7.1: a hostile name stays inside its quotes and literal: " + hostile);
            plan.statements().forEach(statement -> assertEquals(0, statement.parameters().size(),
                    "ADR-0008 §Plans: parameter count equals placeholder count, which is zero in DDL"));
        }
    }

    @Test
    void anIdentifierOf63BytesIsKeptAndOf64BytesIsRefused() {
        String bytes63 = "订".repeat(21);
        String other63 = "é".repeat(31) + "a";
        String bytes64 = "订".repeat(21) + "a";
        assertEquals(63, bytes63.getBytes(StandardCharsets.UTF_8).length);
        assertEquals(63, other63.getBytes(StandardCharsets.UTF_8).length);

        String ddl = String.join("\n", sql(PAIR.target().ddlPlan(named(bytes63, bytes63, "a".repeat(62), other63))));
        for (String kept : List.of(bytes63, other63, "a".repeat(62) + "e")) {
            assertTrue(ddl.contains("\"" + kept + "\""),
                    "TP §7.1: a 63-byte name is PostgreSQL's limit and is kept exactly: " + kept);
        }
        for (TargetTable table : List.of(named(bytes64, "t", "c", "q"), named("s", bytes64, "c", "q"),
                named("s", "t", bytes64, "q"), named("s", "t", "c", bytes64))) {
            assertThrows(IllegalArgumentException.class, () -> PAIR.target().ddlPlan(table),
                    "TP §7.1: PostgreSQL truncates a 64-byte name, so DDL would create a different object");
        }
    }

    @Test
    void theLiteralRendererKeepsHostileValuesInertAndExact() {
        Map<SqlValue, String> expected = new LinkedHashMap<>();
        expected.put(new SqlValue.Text("it's"), "E'it''s'");
        expected.put(new SqlValue.Text("back\\slash"), "E'back\\\\slash'");
        expected.put(new SqlValue.Text("e\\'"), "E'e\\\\'''");
        expected.put(new SqlValue.Text("$$dollar$$"), "E'$$dollar$$'");
        expected.put(new SqlValue.Text("`tick`\"q\"?"), "E'`tick`\"q\"?'");
        expected.put(new SqlValue.Text("new\nline\r\t"), "E'new\\u000Aline\\u000D\\u0009'");
        expected.put(new SqlValue.Text(""), "E'\\u0001\\u007F\\u0085'");
        expected.put(new SqlValue.Text("客户😀"), "E'客户😀'");
        expected.put(new SqlValue.Text(""), "E''");
        expected.put(new SqlValue.Int64(Long.MIN_VALUE), "-9223372036854775808");
        expected.put(new SqlValue.Decimal(new BigDecimal("-0.50")), "-0.50");
        expected.put(new SqlValue.Decimal(new BigDecimal("1E+3")), "1000");
        expected.put(new SqlValue.Bool(true), "true");
        expected.put(new SqlValue.Bytes(new byte[] {0x00, (byte) 0xFF, 0x27, 0x5C}), "E'\\\\x00ff275c'::bytea");
        for (Map.Entry<SqlValue, String> entry : expected.entrySet()) {
            TargetTable table = table(List.of(new TargetColumn(id("c"), TEXT, Nullability.NULLABLE,
                    Optional.of(new TargetDefault.Literal(entry.getKey())), IdentityIntent.NONE, List.of())), List.of());
            assertEquals("CREATE TABLE \"shop\".\"orders\" (\"c\" text DEFAULT " + entry.getValue() + ")",
                    sql(PAIR.target().ddlPlan(table)).get(0),
                    "ADR-0008 §Plans as amended by #123: the typed literal renderer spells " + entry.getKey());
        }
        List<String> benign = skeleton(sql(PAIR.target().ddlPlan(enumTable("a", "b"))));
        for (String hostile : HOSTILE) {
            assertEquals(benign, skeleton(sql(PAIR.target().ddlPlan(enumTable(hostile, hostile + "2")))),
                    "ADR-0008 §Plans: a hostile ENUM member or default never leaves its literal: " + hostile);
        }
    }

