    // --- Nothing beyond the minimal writable table (ADR-0011 §DDL) ------------------------------------

    private static final Pattern FORBIDDEN = Pattern.compile(
            "\\b(IF\\s+NOT\\s+EXISTS|OR\\s+REPLACE|DROP|CASCADE|CREATE\\s+SCHEMA|GRANT|INDEX|FOREIGN|REFERENCES"
                    + "|COMMENT|COLLATE|CONSTRAINT|UNIQUE|TRIGGER|TRUNCATE|INSERT|UPDATE|DELETE)\\b",
            Pattern.CASE_INSENSITIVE);

    @Test
    void ddlCarriesNoForbiddenTokenOutsideItsQuotedNamesAndLiterals() {
        List<TargetTable> tables = new ArrayList<>(List.of(orders(), toggles().get("primary key")));
        HOSTILE.forEach(hostile -> tables.add(named(hostile, hostile, hostile + "c", hostile + "q")));
        tables.add(enumTable("DROP TABLE x CASCADE", "CREATE INDEX i ON t (c) COLLATE \"C\""));
        for (TargetTable table : tables) {
            for (String statement : skeleton(sql(PAIR.target().ddlPlan(table)))) {
                assertFalse(FORBIDDEN.matcher(statement).find(),
                        "ADR-0011 §DDL: DDL never reuses, replaces, drops, grants, indexes, references, comments, "
                                + "collates or names a constraint: " + statement);
                assertTrue(statement.startsWith("CREATE TABLE ") || statement.startsWith("CREATE SEQUENCE ")
                                || statement.startsWith("ALTER SEQUENCE "),
                        "ADR-0011 §DDL: only the table and its owned sequence are created: " + statement);
            }
        }
    }

    // --- Inconsistent tables are refused (ADR-0011 §DDL; TP §7.3) ------------------------------------

    @Test
    void anInconsistentTableCannotBeConstructed() {
        TargetColumn plain = new TargetColumn(id("c"), BIGINT, Nullability.NOT_NULL);
        Map<String, Supplier<Object>> inconsistent = new LinkedHashMap<>();
        inconsistent.put("a key column not in the table", () -> table(List.of(plain), List.of(id("missing"))));
        inconsistent.put("a key column twice", () -> table(List.of(plain), List.of(id("c"), id("c"))));
        inconsistent.put("a nullable key column", () -> table(
                List.of(new TargetColumn(id("c"), BIGINT, Nullability.NULLABLE)), List.of(id("c"))));
        inconsistent.put("a column twice", () -> table(List.of(plain, plain), List.of()));
        for (TargetType nonInteger : List.of(NUMERIC_20_0, TEXT, new TargetType(TargetTypeName.REAL, List.of()))) {
            inconsistent.put("identity on " + nonInteger, () -> new TargetColumn(id("c"), nonInteger,
                    Nullability.NOT_NULL, Optional.empty(), IdentityIntent.IDENTITY_BY_DEFAULT, List.of()));
        }
        for (TargetType notNumeric20 : List.of(BIGINT, NUMERIC_10_2, new TargetType(TargetTypeName.NUMERIC, List.of(20, 1)),
                new TargetType(TargetTypeName.NUMERIC, List.of(19, 0)))) {
            inconsistent.put("owned sequence on " + notNumeric20, () -> new TargetColumn(id("c"), notNumeric20,
                    Nullability.NOT_NULL, Optional.empty(), new IdentityIntent.OwnedSequence(id("q")), List.of()));
        }
        inconsistent.put("a nullable identity", () -> new TargetColumn(id("c"), BIGINT, Nullability.NULLABLE,
                Optional.empty(), IdentityIntent.IDENTITY_BY_DEFAULT, List.of()));
        inconsistent.put("an identity with a default", () -> new TargetColumn(id("c"), BIGINT, Nullability.NOT_NULL,
                Optional.of(new TargetDefault.Literal(new SqlValue.Int64(1))), IdentityIntent.IDENTITY_BY_DEFAULT,
                List.of()));
        inconsistent.put("two generated columns", () -> table(List.of(
                new TargetColumn(id("a"), BIGINT, Nullability.NOT_NULL, Optional.empty(),
                        IdentityIntent.IDENTITY_BY_DEFAULT, List.of()),
                new TargetColumn(id("b"), BIGINT, Nullability.NOT_NULL, Optional.empty(),
                        IdentityIntent.IDENTITY_BY_DEFAULT, List.of())), List.of()));
        inconsistent.put("a sequence named like its table", () -> table(List.of(new TargetColumn(id("id"), NUMERIC_20_0,
                Nullability.NOT_NULL, Optional.empty(), new IdentityIntent.OwnedSequence(id("orders")), List.of())),
                List.of()));
        inconsistent.put("LOCALTIMESTAMP on a non-timestamp", () -> new TargetColumn(id("c"), TEXT, Nullability.NULLABLE,
                Optional.of(new TargetDefault.LocalTimestamp(3)), IdentityIntent.NONE, List.of()));
        inconsistent.put("LOCALTIMESTAMP at another precision", () -> new TargetColumn(id("c"), TIMESTAMP_3,
                Nullability.NULLABLE, Optional.of(new TargetDefault.LocalTimestamp(0)), IdentityIntent.NONE, List.of()));
        inconsistent.put("ENUM members on a non-text target", () -> new TargetColumn(id("c"), BIGINT,
                Nullability.NULLABLE, Optional.empty(), IdentityIntent.NONE, List.of("a")));
        inconsistent.put("duplicate ENUM members", () -> new TargetColumn(id("c"), TEXT, Nullability.NULLABLE,
                Optional.empty(), IdentityIntent.NONE, List.of("a", "a")));
        inconsistent.put("a NULL literal default", () -> new TargetDefault.Literal(new SqlValue.Null(SqlValue.Type.TEXT)));

        for (Map.Entry<String, Supplier<Object>> entry : inconsistent.entrySet()) {
            assertThrows(IllegalArgumentException.class, entry.getValue()::get,
                    "ADR-0011 §DDL: a table whose DDL could not be proven equal to it is refused: " + entry.getKey());
        }
        assertThrows(IllegalArgumentException.class, () -> PAIR.target().ddlPlan(table(List.of(new TargetColumn(id("c"),
                        new TargetType(TargetTypeName.VARCHAR, List.of()), Nullability.NULLABLE)), List.of())),
                "TP §6.3: varchar without its length is not an exact type");
    }

