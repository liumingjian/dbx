    /** Every name position filled from the arguments, with an owned sequence, a key and an ENUM CHECK. */
    private static TargetTable named(String schema, String table, String column, String sequence) {
        return new TargetTable(new TargetTableCoordinate(id(schema), id(table)), List.of(
                new TargetColumn(id(column), NUMERIC_20_0, Nullability.NOT_NULL, Optional.empty(),
                        new IdentityIntent.OwnedSequence(id(sequence)), List.of()),
                new TargetColumn(id(column + "e"), TEXT, Nullability.NULLABLE, Optional.empty(), IdentityIntent.NONE,
                        List.of("a"))),
                List.of(id(column)));
    }

    private static TargetTable enumTable(String first, String second) {
        return table(List.of(new TargetColumn(id("c"), TEXT, Nullability.NULLABLE,
                Optional.of(new TargetDefault.Literal(new SqlValue.Text(first))), IdentityIntent.NONE,
                List.of(first, second))), List.of());
    }

    private static TargetTable replace(TargetTable table, int index, TargetColumn column) {
        List<TargetColumn> columns = new ArrayList<>(table.columns());
        columns.set(index, column);
        return new TargetTable(table.table(), columns, table.primaryKey());
    }

    private static List<String> sql(SqlPlan plan) {
        return plan.statements().stream().map(ParameterizedStatement::sql).toList();
    }

    private static void assertAllDistinct(TargetTable base, Map<String, TargetTable> variants) {
        Map<PlanFingerprint, String> seen = new HashMap<>();
        seen.put(PAIR.target().ddlPlan(base).fingerprint(), "base");
        for (Map.Entry<String, TargetTable> variant : variants.entrySet()) {
            String previous = seen.put(PAIR.target().ddlPlan(variant.getValue()).fingerprint(), variant.getKey());
            assertEquals(null, previous, "ADR-0008 §Plans: changing only the " + variant.getKey()
                    + " must change the fingerprint, but it equals " + previous);
        }
    }

    /**
     * The statement with every double-quoted identifier replaced by {@code "_"} and every escape-string literal
     * by {@code E'_'}: what remains is the structure a hostile name or value must not change.
     */
    private static List<String> skeleton(List<String> statements) {
        return statements.stream().map(TargetDialectContractTest::skeleton).toList();
    }

    private static String skeleton(String sql) {
        StringBuilder out = new StringBuilder();
        for (int i = 0; i < sql.length(); i++) {
            char c = sql.charAt(i);
            if (c == '"') {
                i++;
                while (!(sql.charAt(i) == '"' && (i + 1 == sql.length() || sql.charAt(i + 1) != '"'))) {
                    i += sql.charAt(i) == '"' ? 2 : 1;
                }
                out.append("\"_\"");
            } else if (c == '\'') {
                i++;
                while (!(sql.charAt(i) == '\'' && (i + 1 == sql.length() || sql.charAt(i + 1) != '\''))) {
                    i += sql.charAt(i) == '\'' || sql.charAt(i) == '\\' ? 2 : 1;
                }
                out.append("'_'");
            } else {
                out.append(c);
            }
        }
        return out.toString();
    }
